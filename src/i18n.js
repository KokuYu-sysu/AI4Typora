export function detectUiLanguage() {
  const value = typeof navigator === "undefined"
    ? "en"
    : navigator.language || navigator.languages?.[0] || "en";
  return /^zh/i.test(value) ? "zh-CN" : "en";
}

export function normalizeUiLanguage(value, fallback = detectUiLanguage()) {
  if (value === "zh-CN" || value === "en") return value;
  return fallback === "zh-CN" || fallback === "en" ? fallback : detectUiLanguage();
}

export function translate(language, key, params = {}) {
  const template = UI_CATALOG[normalizeUiLanguage(language)]?.[key];
  if (template === undefined) throw new Error("Unknown AI Edit UI string: " + key);
  return template.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ""));
}
